/** Rows in one category, in declaration order. */
export function sourcesIn(category: SourceCategory): SourceEntry[] {
  return SOURCES.filter((entry) => entry.category === category);
}

/** How many rows in a category the product answers natively. */
export function nativeCount(category: SourceCategory): number {
  return sourcesIn(category).filter((entry) => entry.coverage === "native").length;
}

/** Total native rows. A function so a caller cannot capture a stale count. */
export function nativeTotal(): number {
  return SOURCES.filter((entry) => entry.coverage === "native").length;
}
