export type SourceEntry = {
  /** Stable id, used as the React key and in the URL fragment. */
  id: string;
  name: string;
  category: SourceCategory;
  /** What question this source answers, in one line, imperative mood. */
  answers: string;
  /** Where a person uses it by hand. */
  url: string;
  /** Free, free tier, paid, key required. Kept short and factual. */
  cost: string;
  coverage: ToolCoverage;
  barrier: AccessBarrier;
  /**
   * The check that queries it, when coverage is `native`. Must match a real
   * check id; the sources page asserts this against the live registry.
   */
  checkId?: string;
  /**
   * What the browser cannot do that the tool can, or what a visitor loses by
   * using this product instead. Required when coverage is `reference`.
   */
  gap?: string;
  /** One sentence on how the check reads it, when coverage is `native`. */
  how?: string;
};

