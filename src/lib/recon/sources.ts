/**
 * The source catalogue: every index, API and scanner this project knows about,
 * what it answers, and why it can or cannot be queried from a static page in a
 * visitor's browser.
 *
 * This is the product's honesty surface. A person arrives with a list of tools
 * they have heard of ("does it do VirusTotal? does it do Shodan?") and this
 * catalogue answers for every one of them. Two rules govern it:
 *
 *  1. A row is `native` only when a check in `src/lib/checks` actually queries
 *     that host from the browser. If no check calls it, the row is not native,
 *     however good the API is.
 *  2. A row that is not native states the real reason. "Needs an API key",
 *     "sends no CORS header" and "requires a raw socket" are different facts,
 *     and a reader deciding whether to open the tool deserves the true one.
 *
 * The `url` on each row is where a person goes to use the service by hand, so a
 * gap is a signpost rather than a dead end.
 */

import type { ToolCoverage } from "../types";

/**
 * Why a browser-only page cannot query a source. This drives the filtering and
 * the badge on the sources page, so it is a closed set rather than prose.
 */
export type AccessBarrier =
  /** Sends `Access-Control-Allow-Origin`, so a browser reads it directly. */
  | "cors-open"
  /** Reachable only through the reader proxy, which re-serializes the body. */
  | "reader-proxied"
  /** Works, but requires an API key the visitor has to hold. */
  | "api-key"
  /** Needs a raw socket, a SYN, a TLS handshake or traffic a page cannot send. */
  | "raw-socket"
  /** Serves a web UI only; no machine-readable endpoint a page can read. */
  | "web-only"
  /** Requires a paid plan before any request is accepted. */
  | "paid-plan";

